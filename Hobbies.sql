DROP TABLE IF EXISTS REALIZACION_HOBBY, ESTUDIANTE_HOBBY, ESTUDIANTE, HOBBY, RECOMPENSA CASCADE;

CREATE TABLE ESTUDIANTE (
    ID INT PRIMARY KEY,
    NOMBRE VARCHAR(100),
    EDAD INT,
    CORREO_ELECTRONICO VARCHAR(100)
);

CREATE TABLE HOBBY (
    ID INT PRIMARY KEY,
    NOMBRE VARCHAR(100)
);

CREATE TABLE ESTUDIANTE_HOBBY (
    ESTUDIANTE_ID INT,
    HOBBY_ID INT,
    PRIMARY KEY (ESTUDIANTE_ID, HOBBY_ID),
    FOREIGN KEY (ESTUDIANTE_ID) REFERENCES ESTUDIANTE(ID),
    FOREIGN KEY (HOBBY_ID) REFERENCES HOBBY(ID)
);

CREATE TABLE RECOMPENSA (
    ID INT PRIMARY KEY,
    NOMBRE VARCHAR(100),
    VALOR INT
);

CREATE TABLE REALIZACION_HOBBY (
    ID INT PRIMARY KEY,
    ESTUDIANTE_ID INT,
    HOBBY_ID INT,
    RECOMPENSA_ID INT,
    FECHA DATE,
    FOREIGN KEY (ESTUDIANTE_ID, HOBBY_ID)
        REFERENCES ESTUDIANTE_HOBBY(ESTUDIANTE_ID, HOBBY_ID),
    FOREIGN KEY (RECOMPENSA_ID) REFERENCES RECOMPENSA(ID)
);

